-- FashionScape Bot v3 - Audit log
-- Flyway V3: Record staff actions and outfit changes, and where to post them

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(64) NOT NULL,
    actor_id VARCHAR(64) NOT NULL,
    guild_id VARCHAR(64),
    target_type VARCHAR(32),
    target_id VARCHAR(64),
    details TEXT,
    created TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_audit_log_created ON audit_log(created);
CREATE INDEX IF NOT EXISTS idx_audit_log_target ON audit_log(target_type, target_id);

-- Bot-wide settings, such as the audit channel
CREATE TABLE IF NOT EXISTS bot_settings (
    setting_key VARCHAR(64) PRIMARY KEY,
    setting_value TEXT NOT NULL,
    updated TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
