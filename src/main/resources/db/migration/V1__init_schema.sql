-- FashionScape Bot v3 - Initial Schema Migration
-- Flyway V1: Core Relational Schema

-- Outfits table
CREATE TABLE IF NOT EXISTS outfits (
    id VARCHAR(64) PRIMARY KEY,
    link TEXT NOT NULL,
    submitter VARCHAR(64) NOT NULL,
    tag VARCHAR(255),
    meta TEXT,
    discord_name VARCHAR(255),
    created TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    display_count INTEGER NOT NULL DEFAULT 0,
    delete_hash VARCHAR(255)
);

CREATE INDEX IF NOT EXISTS idx_outfits_submitter ON outfits(submitter);
CREATE INDEX IF NOT EXISTS idx_outfits_tag ON outfits(tag);
CREATE INDEX IF NOT EXISTS idx_outfits_deleted ON outfits(deleted);
CREATE INDEX IF NOT EXISTS idx_outfits_featured ON outfits(featured);

-- Gallery channels table
CREATE TABLE IF NOT EXISTS gallery_channels (
    channel_id VARCHAR(64) PRIMARY KEY,
    server_id VARCHAR(64) NOT NULL,
    emoji VARCHAR(255),
    tag VARCHAR(255),
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS idx_gallery_channels_server_id ON gallery_channels(server_id);

-- Server configurations table
CREATE TABLE IF NOT EXISTS server_configs (
    id VARCHAR(64) PRIMARY KEY,
    prefix VARCHAR(32) DEFAULT '~',
    welcome_message TEXT,
    welcome_channel VARCHAR(64)
);

-- Blocked users table
CREATE TABLE IF NOT EXISTS blocked_users (
    id VARCHAR(64) PRIMARY KEY,
    reason TEXT,
    added TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Blocked servers table
CREATE TABLE IF NOT EXISTS blocked_servers (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(255),
    owner_id VARCHAR(64),
    reason TEXT,
    added TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Static permissions table
CREATE TABLE IF NOT EXISTS static_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    permission VARCHAR(64) NOT NULL,
    added TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_static_permissions_user ON static_permissions(user_id);

-- Color roles table
CREATE TABLE IF NOT EXISTS color_roles (
    role_id VARCHAR(64) PRIMARY KEY,
    server_id VARCHAR(64) NOT NULL,
    color VARCHAR(32),
    group_id VARCHAR(64)
);

CREATE INDEX IF NOT EXISTS idx_color_roles_server ON color_roles(server_id);
